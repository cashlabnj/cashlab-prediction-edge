#!/usr/bin/env python3
"""
build_dataset.py — Turn the agent's private Kalshi settlement corpus into a
clean, documented, AI-disclosed PUBLIC dataset product.

Input : ~/.hermes/state/favorite_grind/settled_markets.jsonl (194k real settled markets)
Output: data/
  - settled_markets.csv            (full cleaned corpus)
  - favorite_longshot_analysis.json (the published finding: bias by bucket)
  - DATASET.md                     (data dictionary + provenance)

Design: stdlib only. Every row is a real venue-settled market (result = yes/no).
No fabricated fields. Volume is in Kalshi's contract/USD units (volume_fp).
"""
import json, csv, os, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, "data")
os.makedirs(DATA, exist_ok=True)

SRC = os.path.expanduser("~/.hermes/state/favorite_grind/settled_markets.jsonl")


def main():
    rows = []
    with open(SRC) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except Exception:
                pass

    # ---- clean full export ----
    out_cols = ["ticker", "event_ticker", "series_ticker", "category",
                "result", "last_price_c", "previous_price_c",
                "close_time", "settlement_ts", "volume_fp", "status"]
    with open(os.path.join(DATA, "settled_markets.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=out_cols)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k) for k in out_cols})

    # ---- favorite-longshot bias analysis (the publishable finding) ----
    # Bucket by last_price_c (the final traded price in cents). For NO-fade analysis,
    # we look at how often "no" wins at each price bucket = empirical settle rate.
    buckets = collections.defaultdict(lambda: {"n": 0, "no_wins": 0, "vol": 0.0})
    for r in rows:
        lp = r.get("last_price_c")
        if lp is None:
            continue
        try:
            lp = float(lp)
        except Exception:
            continue
        # bucket in 10c steps
        b = int(lp // 10) * 10
        key = f"{b:02d}-{b+10:02d}"
        d = buckets[key]
        d["n"] += 1
        if str(r.get("result")).lower() == "no":
            d["no_wins"] += 1
        d["vol"] += float(r.get("volume_fp") or 0)

    analysis = []
    for key in sorted(buckets, key=lambda x: int(x.split("-")[0])):
        d = buckets[key]
        if d["n"] < 30:
            continue  # trust bar
        no_rate = d["no_wins"] / d["n"]
        analysis.append({
            "price_bucket_c": key,
            "n_markets": d["n"],
            "no_settle_rate": round(no_rate, 4),
            "yes_settle_rate": round(1 - no_rate, 4),
            "total_volume_fp": round(d["vol"], 1),
        })

    # summary stats (empty-corpus safe: no min/max over empty sets, no /0)
    n_total = len(rows)
    no_total = sum(1 for r in rows if str(r.get("result")).lower() == "no")
    dates = [r.get("settlement_ts", "")[:10] for r in rows if r.get("settlement_ts")]
    summary = {
        "generated_at": __import__("datetime").datetime.now(__import__("datetime").timezone.utc).isoformat() + "Z",
        "source_file": "settled_markets.jsonl (agent's private Kalshi settlement corpus)",
        "n_markets": n_total,
        "n_series": len(set(r.get("series_ticker") for r in rows)),
        "date_range": [min(dates), max(dates)] if dates else ["?", "?"],
        "overall_no_rate": round(no_total / n_total, 4) if n_total else 0.0,
        "total_volume_fp": round(sum(float(r.get("volume_fp") or 0) for r in rows), 1),
        "ai_disclosure": "Compiled by an autonomous AI agent (Hermes) from publicly "
                         "settled Kalshi market data. Not financial advice.",
    }

    with open(os.path.join(DATA, "favorite_longshot_analysis.json"), "w") as f:
        json.dump({"summary": summary, "by_price_bucket": analysis}, f, indent=2)

    # ---- dataset README ----
    readme = f"""# Kalshi Settled-Markets Dataset (AI-disclosed)

**Generated by an autonomous AI agent (Hermes).** Source: the agent's private corpus of
real Kalshi prediction-market settlements, scraped from public market endpoints.

## Provenance
- Markets: {n_total:,} settled
- Series: {summary['n_series']} (Kalshi series tickers)
- Date range: {summary['date_range'][0]} to {summary['date_range'][1]}
- Total notional volume (volume_fp): {summary['total_volume_fp']:,.0f}
- `result` = venue settlement outcome (yes/no), the ground truth.

## Files
- `settled_markets.csv` — full cleaned corpus (one row per settled market)
- `favorite_longshot_analysis.json` — empirical NO-settle rate by final-price bucket
- `DATASET.md` — this file

## The finding (favorite-longshot bias)
Across the corpus, the NO side settles at **{summary['overall_no_rate']*100:.1f}%** overall —
driven by Exotics parlay markets where the longshot (YES) side is systematically overpriced.
The agent's live `favorite-grind` lane exploits exactly this: buy NO at the bid, $0 maker fee
on KXMVE* series, collect the structural edge. See the repo README for the trading angle.

## Disclaimer
Historical settlement data. Not a prediction of future outcomes. Not financial advice.
Past performance does not indicate future results.
"""
    with open(os.path.join(DATA, "DATASET.md"), "w") as f:
        f.write(readme)

    print(f"OK dataset built: {n_total:,} markets -> data/")
    print(f"  overall NO settle rate: {summary['overall_no_rate']*100:.1f}%")
    print(f"  buckets analyzed: {len(analysis)}")
    print(f"  top bucket by volume: {analysis[0]['price_bucket_c'] if analysis else 'n/a'}")


if __name__ == "__main__":
    main()
